import {readFile,writeFile} from 'node:fs/promises';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'../..');
const oldPair='db/deploy-contract/postflight-168.sql';
export async function expand(file,stack=[]){
 if(stack.includes(file))throw Error('Postflight include cycle');
 const source=await readFile(path.join(root,file),'utf8');let result='',offset=0;
 for(const match of source.matchAll(/^\\i\s+(\S+)[ \t]*$/gm)){
  result+=source.slice(offset,match.index)+await expand(match[1],[...stack,file]);offset=match.index+match[0].length;
 }
 return result+source.slice(offset);
}
// Inline only ancestors of168. Keep every other include and check untouched,
// including the entire historical167-and-earlier graph and all named probes.
export async function renderKnownPostflight(file){
 const cache=new Map();
 async function render(current,stack=[]){
  if(stack.includes(current))throw Error('Postflight include cycle');
  if(cache.has(current))return cache.get(current);
  if(current===oldPair)return {changed:true,source:'\\i db/deploy-contract/postflight-167.sql\n\\i db/deploy-contract/training-pair-compatibility-probe-368.sql\n'};
  const source=await readFile(path.join(root,current),'utf8');let result='',offset=0,changed=false;
  for(const match of source.matchAll(/^\\i\s+(\S+)[ \t]*$/gm)){
   const child=await render(match[1],[...stack,current]);
   changed ||= child.changed;
   result+=source.slice(offset,match.index)+(child.changed?child.source:match[0]);offset=match.index+match[0].length;
  }
  const value={changed,source:result+source.slice(offset)};cache.set(current,value);return value;
 }
 const value=await render(file);if(!value.changed)throw Error('Expected inherited168 boundary');
 return '-- Generated by db/scripts/generate_known_postflight.mjs; historical files stay unchanged.\n'+value.source;
}
if(process.argv[1]===fileURLToPath(import.meta.url)){
 for(const prefix of ['postflight','read-only-postflight']){
  const file=`db/deploy-contract/${prefix}-365-known-368.sql`,source=await renderKnownPostflight(`db/deploy-contract/${prefix}-365.sql`);
  if(process.argv.includes('--check')){if(await readFile(path.join(root,file),'utf8')!==source)throw Error(`Generated postflight drift: ${file}`);}
  else await writeFile(path.join(root,file),source);
 }
}
