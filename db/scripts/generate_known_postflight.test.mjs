import {test} from 'node:test';
import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import {expand,renderKnownPostflight} from './generate_known_postflight.mjs';
const compact=sql=>sql.replace(/^\s*\n/gm,'');
test('DB368 retains every inherited check, versioning only the delegated pair owner',async()=>{
 const oldPair=(await readFile('db/deploy-contract/postflight-168.sql','utf8')).replace(/^\\i[^\n]*\n/,'');
 const newPair=await expand('db/deploy-contract/training-pair-compatibility-probe-368.sql');
 for(const prefix of ['postflight','read-only-postflight']){
  const generated=`db/deploy-contract/${prefix}-365-known-368.sql`;
  assert.equal(await readFile(generated,'utf8'),await renderKnownPostflight(`db/deploy-contract/${prefix}-365.sql`));
  const prior=await expand(`db/deploy-contract/${prefix}-365.sql`);
  assert.equal(prior.split(oldPair).length,2);
  let expected=prior.replace(oldPair,()=>newPair);
  for(const probe of ['training-history-probe.sql','training-history-actions-probe.sql','question-reminder-preference-probe.sql','starter-editorial-collection-probe.sql'])expected+='\n'+await expand('db/deploy-contract/'+probe);
  const actual=(await expand(`db/deploy-contract/${prefix}-368.sql`)).replace(/^-- Generated by db\/scripts\/generate_known_postflight.mjs; historical files stay unchanged.\n/,'');
  assert.equal(compact(actual),compact(expected));
 }
});
