import { expect, test } from '@playwright/test';
import { execFileSync } from 'node:child_process';
import { readFileSync } from 'node:fs';
import { getUiMessages } from '../../lib/uiMessages';
import { organizationCopy } from '../../components/library/organization/copy';
import { platformV2Message } from '../../lib/platform/platformV2ClientI18n';

const uuid = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i;
test('collection persists through real browser, API and database', async ({ page, request }) => {
  const dbPort = process.env.REAL_SMOKE_DB_PORT ?? '';
  if (!/^\d{4,5}$/.test(dbPort) || !process.env.REAL_SMOKE_QA_FILE) throw new Error('Missing isolated database identity');
  const qa = JSON.parse(readFileSync(process.env.REAL_SMOKE_QA_FILE, 'utf8'));
  expect(qa.id).toMatch(uuid);
  const health = await (await request.get('/api/health?deep=1')).json();
  expect(health.status).toBe('ok'); expect(health.database.target).toBe('local');
  await page.setViewportSize({ width: 1280, height: 900 });
  await page.goto('/dev/test-login?redirectTo=/');
  await page.waitForURL(url => url.pathname === '/', { timeout: 60_000 });
  const pause = page.getByRole('button', { name: 'Pause tour' });
  await expect(pause).toBeVisible({ timeout: 30_000 });
  await pause.click();
  await page.getByRole('button', { name: 'Library', exact: true }).click();
  const nav = page.getByRole('navigation', { name: 'Library' });
  const org = organizationCopy('en'), ui = getUiMessages('en');
  const message = (key: string) => platformV2Message('en', key);
  await nav.getByRole('button', { name: org.collections, exact: true }).click();
  await page.getByTestId('personal-collections').waitFor();
  await page.getByRole('button', { name: org.newCollection, exact: true }).click();
  const name = `Smoke ${Date.now()}`;
  await page.getByRole('dialog').getByRole('textbox').fill(name);
  const created = page.waitForResponse(r => new URL(r.url()).pathname === '/rest/v1/rpc/create_user_word_list' && r.ok());
  await page.getByRole('dialog').getByRole('button', { name: org.save, exact: true }).click();
  const payload = await (await created).json();
  const listId = Array.isArray(payload) ? payload[0]?.id : payload.id;
  expect(listId).toMatch(uuid);
  await nav.getByRole('button', { name: 'Words', exact: true }).click();
  const searched = page.waitForResponse(r => new URL(r.url()).pathname === '/api/library/category-search' && r.ok());
  await page.getByRole('textbox', { name: ui.library.search, exact: true }).fill('bank');
  await searched;
  await page.getByTestId('library-headword-group-row').first().click();
  const cards = page.locator('article[data-entry-id][data-testid^="library-sense-card-"]:visible');
  await expect(cards.first()).toBeVisible();
  const entryId = (await cards.first().getAttribute('data-entry-id'))!;
  expect(entryId).toMatch(uuid);
  const card = (id: string) => page.locator(`article[data-entry-id="${id}"]:visible`);
  if (await card(entryId).getAttribute('data-expanded') !== 'true') await card(entryId).getByRole('button', { name: message('senseCard.expand'), exact: true }).click();
  await card(entryId).getByRole('button', { name: new RegExp(`^${message('senseCard.collections.label')}`) }).click();
  const choice = page.getByRole('dialog').getByRole('checkbox', { name: new RegExp(name) });
  const added = page.waitForResponse(r => new URL(r.url()).pathname === '/rest/v1/rpc/add_entry_to_user_list');
  await choice.click(); expect((await added).ok()).toBeTruthy(); await expect(choice).toBeChecked();
  await page.keyboard.press('Escape');
  await nav.getByRole('button', { name: org.collections, exact: true }).click();
  const collectionRead = page.waitForResponse(r => new URL(r.url()).pathname === '/api/library/collection-details' && r.ok());
  await page.getByRole('button', { name, exact: true }).click(); await collectionRead;
  const scopedRead = page.waitForResponse(r => new URL(r.url()).pathname === '/api/library/search' && JSON.stringify(r.request().postDataJSON()).includes(listId));
  await page.getByRole('button', { name: 'View words', exact: true }).click();
  expect((await scopedRead).ok()).toBeTruthy();
  await expect(card(entryId)).toHaveAttribute('data-current-collection', 'included');
  await page.reload();
  await page.getByRole('button', { name: 'Library', exact: true }).click();
  await nav.getByRole('button', { name: org.collections, exact: true }).click();
  await page.getByRole('button', { name, exact: true }).click();
  await page.getByRole('button', { name: 'View words', exact: true }).click();
  await expect(card(entryId)).toHaveAttribute('data-current-collection', 'included');
  const sql = `SELECT count(*) FILTER (WHERE i.word_id='${entryId}'), count(*) FROM public.user_word_list_items i JOIN public.user_word_lists l ON l.id=i.list_id WHERE l.id='${listId}' AND l.user_id='${qa.id}'`;
  const count = execFileSync('psql', ['-X', '-At', '-v', 'ON_ERROR_STOP=1', '-h', '127.0.0.1', '-p', dbPort, '-U', 'postgres', '-d', 'postgres', '-c', sql], { env: { PATH: process.env.PATH, NODE_ENV: 'test', PGPASSWORD: 'postgres' }, encoding: 'utf8' }).trim();
  expect(count).toBe('1|1');
});
