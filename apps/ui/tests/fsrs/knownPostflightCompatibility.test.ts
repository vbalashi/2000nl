import fs from "node:fs";
import path from "node:path";
import {execFileSync} from "node:child_process";
import {Pool} from "pg";
import {beforeAll,afterAll,describe,test,expect} from "vitest";
import {getDbUrl,runMigrations,withTransaction} from "./dbTestUtils";
const root=path.resolve(process.cwd(),"../..");
function expand(file:string):string{
 return fs.readFileSync(path.join(root,file),"utf8").replace(/^\\i (.+)$/gm,(_,child:string)=>expand(child.trim()));
}
test("versioned368 graph retains every inherited check and exact generated bytes",()=>{
 execFileSync(process.execPath,['--test','db/scripts/generate_known_postflight.test.mjs'],{cwd:root});
});
const url=getDbUrl();
(url?describe:describe.skip)("installed pair owner compatibility",()=>{
 const pool=new Pool({connectionString:url});beforeAll(()=>runMigrations(pool));afterAll(()=>pool.end());
 test.each([
  "GRANT EXECUTE ON FUNCTION private.perform_legacy_pair_exclusion_as_principal_v1(uuid,text,uuid,uuid,text,uuid,uuid,uuid) TO authenticated",
  "ALTER FUNCTION public.perform_training_pair_exclusion_as_principal_v1(uuid,text,uuid,uuid,text,uuid,uuid,uuid) SET search_path=public,private,extensions,pg_temp",
 ])("versioned pair gate rejects unsafe authority changes: %s",async mutation=>{
  await withTransaction(pool,async client=>{
   await client.query(mutation);
   const probe=expand('db/deploy-contract/training-pair-compatibility-probe-368.sql').replace('BEGIN READ ONLY;','').replace(/COMMIT;\s*$/,'');
   await client.query('savepoint unsafe_pair_boundary');
   await expect(client.query(probe)).rejects.toThrow('postflight-failed pair-exclusion-actions');
   await client.query('rollback to savepoint unsafe_pair_boundary');
  });
 });
});
