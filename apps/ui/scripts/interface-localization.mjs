#!/usr/bin/env node
import { catalogShape, canonicalJson, catalogErrors as shape } from "../lib/i18n/snapshot-contract.mjs";
import { createHash } from "node:crypto";
import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const uiRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const [command = "report", ...args] = process.argv.slice(2);
const option = name => {
  const index = args.indexOf(`--${name}`);
  return index < 0 ? undefined : args[index + 1];
};
const directory = path.resolve(option("catalog-dir") ?? path.join(uiRoot, "locales"));
const load = filename => JSON.parse(readFileSync(path.join(directory, filename), "utf8"));
const save = (filename, value) => {
  const target = path.join(directory, filename);
  mkdirSync(path.dirname(target), { recursive: true });
  const json = filename.startsWith("reviews/")
    ? `{\n${Object.entries(value).map(([key, entry]) => `  ${JSON.stringify(key)}: ${JSON.stringify(entry)}`).join(",\n")}\n}`
    : JSON.stringify(value, null, 2);
  writeFileSync(target, `${json}\n`);
};
const hash = text => createHash("sha256").update(text).digest("hex");
const own = (value, key) => Object.prototype.hasOwnProperty.call(value, key);
function leaves(value, prefix = "", result = {}) {
  if (typeof value === "string") result[prefix] = value;
  else if (value && typeof value === "object")
    for (const [key, child] of Object.entries(value)) leaves(child, prefix ? `${prefix}.${key}` : key, result);
  return result;
}
function generatedModule(codes, source) {
  return '// Generated by npm run i18n:sync. Register languages in locales/registry.json.\n'
    + codes.map(code => `import ${code} from "@/locales/${code}.json";\n`).join("")
    + 'import type { InterfaceLanguage } from "./registry";\n'
    + 'export type MessageCatalog = typeof en;\n'
    + `export const interfaceCatalogContract = "${hash(canonicalJson(catalogShape(source)))}";\n`
    + `export const interfaceCatalogs = { ${codes.join(", ")} } satisfies Record<InterfaceLanguage, MessageCatalog>;\n`;
}
try {
  const registry = load("registry.json");
  const codes = Object.keys(registry);
  if (!own(registry, "en")) throw new Error("English must be registered as the source locale.");
  for (const code of codes) {
    if (!/^[a-z]{2,3}$/.test(code) || !registry[code].name?.trim() || !["ltr", "rtl"].includes(registry[code].direction)) throw new Error(`Invalid locale registry entry: ${code}`);
  }
  const source = load("en.json"), reference = leaves(source);
  const locale = option("locale");
  if (locale && !/^[a-z]{2,3}$/.test(locale)) throw new Error("Use an ISO language code, for example uk.");
  const targets = locale ? (locale === "en" ? [] : [locale]) : codes.filter(code => code !== "en");
  const generatedPath = option("catalog-dir") ? path.join(directory, "catalogs.generated.ts") : path.join(uiRoot, "lib/i18n/catalogs.generated.ts");
  if (command === "sync") {
    for (const code of codes) {
      const errors = shape(source, load(`${code}.json`));
      if (errors.length) throw new Error(`${code}: catalog is incomplete: ${JSON.stringify(errors.slice(0, 5))}`);
    }
    writeFileSync(generatedPath, generatedModule(codes, source));
    if (!option("catalog-dir")) {
      const manifestPath = path.join(uiRoot, "public/manifest.json");
      const manifest = JSON.parse(readFileSync(manifestPath, "utf8"));
      manifest.name = source.features.appMetadata.title;
      manifest.description = source.features.appMetadata.description;
      writeFileSync(manifestPath, `${JSON.stringify(manifest, null, 2)}\n`);
    }
    console.log("Updated catalog imports and default install metadata. Translation review state was not changed.");
  } else if (command === "add") {
    const key = option("key"), text = option("text");
    const segments = key?.split(".") ?? [];
    if (!segments.length || segments.some(segment => !/^[a-zA-Z][a-zA-Z0-9]*$/.test(segment) || ["__proto__", "prototype", "constructor"].includes(segment))) throw new Error("Specify a safe object message key, for example --key ui.settings.translationAttribution.");
    if (typeof text !== "string" || !text.trim()) throw new Error("Specify non-empty English source text with --text.");
    // Include prepared drafts too; no language silently loses a newly added message.
    const catalogCodes = readdirSync(directory).filter(filename => /^[a-z]{2,3}\.json$/.test(filename)).map(filename => filename.slice(0, -5));
    if (codes.some(code => !catalogCodes.includes(code))) throw new Error("A registered locale catalog is missing.");
    const plans = catalogCodes.map(code => {
      const catalog = load(`${code}.json`);
      let parent = catalog;
      for (const segment of segments.slice(0, -1)) {
        if (!own(parent, segment)) parent[segment] = {};
        if (!parent[segment] || typeof parent[segment] !== "object" || Array.isArray(parent[segment])) throw new Error(`${code}: ${segment} is not an object section.`);
        parent = parent[segment];
      }
      const leaf = segments.at(-1);
      if (own(parent, leaf)) throw new Error(`${code}: ${key} already exists; edit existing messages without resetting their review state.`);
      parent[leaf] = text;
      const reviewFile = `reviews/${code}.json`;
      const review = code !== "en" && existsSync(path.join(directory, reviewFile)) ? load(reviewFile) : {};
      delete review[key];
      return {code, catalog, reviewFile, review};
    });
    for (const plan of plans) {
      save(`${plan.code}.json`, plan.catalog);
      if (plan.code !== "en") save(plan.reviewFile, plan.review);
    }
    console.log(`Added ${key} to ${plans.length} catalogs. Non-English entries contain source text and require translation/review; no translation was generated or approved.`);
  } else if (command === "prepare") {
    if (!locale || locale === "en") throw new Error("Use prepare --locale uk (a new non-English locale).");
    if (existsSync(path.join(directory, `${locale}.json`))) throw new Error(`Catalog ${locale} already exists.`);
    save(`${locale}.json`, source);
    save(`reviews/${locale}.json`, {});
    console.log(`Prepared ${locale}.json with English source text. All messages need translation/review; the language is not enabled.`);
  } else if (command === "review") {
    if (!locale || locale === "en") throw new Error("Specify --locale for one translation language.");
    const candidate = load(`${locale}.json`), target = leaves(candidate);
    const keys = args.includes("--all") ? Object.keys(reference) : args.flatMap((value, index) => value === "--key" ? [args[index + 1]] : []);
    if (!keys.length) throw new Error("Specify --key message.path (repeatable), or explicitly --all after reviewing the entire catalog.");
    const errors = shape(source, candidate);
    const reviewFile = `reviews/${locale}.json`;
    const reviews = existsSync(path.join(directory, reviewFile)) ? load(reviewFile) : {};
    for (const key of keys) {
      if (!own(reference, key)) throw new Error(`Unknown source key: ${key}`);
      if (!own(target, key) || errors.some(error => error.key === key || key.startsWith(`${error.key}.`))) throw new Error(`Fix missing text, shape or parameters before reviewing ${key}.`);
      reviews[key] = { source: reference[key], translationHash: hash(target[key]) };
    }
    if (args.includes("--all")) for (const key of Object.keys(reviews)) if (!own(reference, key)) delete reviews[key];
    save(reviewFile, reviews);
    console.log(`Recorded the current source and translation for ${keys.length} messages in ${locale}.`);
  } else if (command === "check" || command === "report") {
    const reports = [];
    for (const code of targets) {
      const candidate = load(`${code}.json`), target = leaves(candidate);
      const reviewFile = `reviews/${code}.json`;
      const reviews = existsSync(path.join(directory, reviewFile)) ? load(reviewFile) : {};
      const issues = shape(source, candidate);
      const invalid = new Set(issues.map(issue => issue.key));
      for (const [key, text] of Object.entries(reference)) {
        if (!own(target, key) || invalid.has(key)) continue;
        const review = reviews[key];
        if (!review) issues.push({key, status: "unreviewed", source: text, translation: target[key]});
        else if (review.source !== text) issues.push({key, status: "outdated", previousSource: review.source, source: text, translation: target[key]});
        else if (review.translationHash !== hash(target[key])) issues.push({key, status: "translation-changed", source: text, translation: target[key]});
      }
      reports.push({locale: code, messages: Object.keys(target).length, issues});
    }
    const words = Object.values(reference).reduce((sum, text) => sum + (text.match(/[\p{L}\p{N}’'-]+/gu)?.length ?? 0), 0);
    if (args.includes("--json")) console.log(JSON.stringify({source: "en", messages: Object.keys(reference).length, words, locales: reports}, null, 2));
    else {
      console.log(`English source: ${Object.keys(reference).length} messages, ${words} words.`);
      for (const report of reports) {
        console.log(`${report.locale}: ${report.issues.length ? `${report.issues.length} issues` : "up to date"}`);
        for (const issue of report.issues) console.log(`  ${issue.status}: ${issue.key}`);
      }
    }
    if (command === "check") {
      if (!option("catalog-dir") && readFileSync(generatedPath, "utf8") !== generatedModule(codes, source)) {
        console.error("Catalog imports are out of date. Run npm run i18n:sync.");
        process.exitCode = 1;
      }
      if (!option("catalog-dir")) {
        const manifest = JSON.parse(readFileSync(path.join(uiRoot, "public/manifest.json"), "utf8"));
        if (manifest.name !== source.features.appMetadata.title || manifest.description !== source.features.appMetadata.description) {
          console.error("Install metadata is out of date. Run npm run i18n:sync.");
          process.exitCode = 1;
        }
      }
      if (reports.some(report => report.issues.length)) process.exitCode = 1;
    }
  } else throw new Error("Commands: report, check, sync, add --key KEY --text TEXT, prepare --locale CODE, review --locale CODE --key KEY|--all");
} catch (error) {
  console.error(error.message);
  process.exitCode = 1;
}
